def md_cell(c):
    return str(c).replace('|', '\\|').replace('\n', ' ')


def to_md(blocks):
    out = []
    for bl in blocks:
        t = bl['t']
        if t == 'h1': out.append('# ' + bl['text'])
        elif t == 'h2': out.append('## ' + bl['text'])
        elif t == 'h3': out.append('### ' + bl['text'])
        elif t == 'p': out.append(bl['text'])
        elif t == 'ul': out.append('\n'.join('- ' + i for i in bl['items']))
        elif t == 'ol': out.append('\n'.join(f'{k + 1}. ' + i for k, i in enumerate(bl['items'])))
        elif t == 'code': out.append('```\n' + bl['text'] + '\n```')
        elif t == 'table':
            lines = [f'**{bl["title"]}**', '', '| ' + ' | '.join(bl['head']) + ' |', '|' + '---|' * len(bl['head'])]
            lines += ['| ' + ' | '.join(md_cell(c) for c in r) + ' |' for r in bl['rows']]
            out.append('\n'.join(lines))
        out.append('')
    return '\n'.join(out)


