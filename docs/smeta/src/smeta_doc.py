def fd(n):
    return ('+' if round(n) > 0 else '') + f(n)


def m(n, d=1):
    return f'{n / 1e6:.{d}f}'.replace('.', ',') + ' млн'


def pct(new, old):
    if old == 0:
        return '0 %' if new == 0 else 'новая статья'
    p = (new - old) / old * 100
    return ('+' if p > 0 else ('−' if p < 0 else '')) + f'{abs(p):.0f}' + ' %'


